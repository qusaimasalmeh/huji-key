export const MESSAGES: Record<Language, Record<MessageKey, string>> = { en, he, ar };

/** Returns the CSS writing direction ('ltr' or 'rtl') for the given language. */
export function getDirection(lang: Language): 'ltr' | 'rtl' {
  return lang === 'en' ? 'ltr' : 'rtl';
}

/** Translates a message key for the given language and interpolates `{placeholder}` variables. */
export function t(
  lang: Language,
  key: MessageKey,
  vars?: Record<string, string | number>
): string {
  const dict = MESSAGES[lang] ?? MESSAGES.en;
  let template = dict[key] ?? MESSAGES.en[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      template = template.replaceAll(`{${k}}`, String(v));
    }
  }
  return template;
}

/** Applies the language and writing direction attributes to the document root element. */
export function applyDocumentLocale(doc: Document, lang: Language): void {
  doc.documentElement.lang = lang;
  doc.documentElement.dir = getDirection(lang);
}
